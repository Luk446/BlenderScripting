"""Blender dataset generator. Outputs PNGs and metadata, not YOLO annotations.

Run with blender_pylauncher.py. Distances are Blender units. Each run has its own
folder. Temporary changes are restored on completion, cancellation or failure.
"""
import csv
import json
import math
import random
from datetime import datetime
from pathlib import Path
import bpy
from mathutils import Matrix, Vector
from bpy_extras.object_utils import world_to_camera_view

# -----------------------------------------------------------------------------
# EDITABLE SETTINGS - change these values before running the Blender launcher
# -----------------------------------------------------------------------------
# Distances below use Blender scene units. A (minimum, maximum) pair selects a
# random value in that range for each image. Equal endpoints give a fixed value.
# Render engine, samples, exposure, materials and camera lens come from Blender.

# -----------------------------------------------------------------------------
# OUTPUT - number of images, image size and save location
# -----------------------------------------------------------------------------
NUMBER_OF_IMAGES = 20  # Number of images generated by one run.
OUTPUT_FOLDER = r"C:\Users\Luke\Pictures\MooringChainWorkImages\BlenderSimDataset"
IMAGE_WIDTH = 640   # Pixels across the image.
IMAGE_HEIGHT = 640  # Pixels down the image.
# A new run_... subfolder is created for each batch to avoid overwriting images.

# -----------------------------------------------------------------------------
# RANDOMNESS AND TESTING - repeat a batch or check placement without rendering
# -----------------------------------------------------------------------------
MASTER_SEED = None  # None = new choices; an integer (e.g. 42) repeats choices.
DRY_RUN = False  # True = placement checks and metadata only; no PNGs.
FORCE_STRUCTURES_FOR_TEST = False  # True requests all structures in every image.
# Unsafe or unseen structures are still skipped, even when forced.

# -----------------------------------------------------------------------------
# LIGHT STRENGTH - power of Light_Left and Light_Right
# -----------------------------------------------------------------------------
# A shared base power is selected per image, then each light gets its own
# multiplier. Increase the power values for brighter lighting.
MIN_BASE_POWER = 300  # Minimum base power in watts for point/spot/area lights.
MAX_BASE_POWER = 375  # Maximum base power in watts.
MIN_LIGHT_MULTIPLIER = 0.9  # Up to 10% below the selected base power.
MAX_LIGHT_MULTIPLIER = 1.1  # Up to 10% above the selected base power.
# For fixed equal lights: set both powers to e.g. 350 and both multipliers to 1.

# -----------------------------------------------------------------------------
# LIGHT POSITION - offsets from the camera, in scene units
# -----------------------------------------------------------------------------
LIGHT_SIDE_OFFSET = 0.35  # Each light sits this far left/right of the camera.
LIGHT_FORWARD_OFFSET = 0.15  # Positive moves lights forward towards the subject.
# Lights follow the camera orientation. Edit light colour/type/size in Blender.

# -----------------------------------------------------------------------------
# CAMERA POSITION AND FRAMING - random offsets from the chain centre
# -----------------------------------------------------------------------------
CAMERA_X_RANGE = 4.0  # X offset is selected between -4 and +4.
CAMERA_Y_RANGE = 4.0  # Y offset is selected between -4 and +4.
CAMERA_Z_MIN = 1.0  # Minimum height ABOVE the chain centre (not seabed height).
CAMERA_Z_MAX = 5.0  # Maximum height above the chain centre.
MIN_VISIBLE_LINK_CENTRES = 3  # Minimum link centres inside the camera frame.
# Larger X/Y ranges allow more distant views. Lens/focal length is set in Blender.
# This allows close-ups and cropped links; it does not require the whole chain.

# -----------------------------------------------------------------------------
# SEABED VARIATION - choose one Seabed_ mesh, or leave all seabeds hidden
# -----------------------------------------------------------------------------
NO_SEABED_PROBABILITY = 0.15
# Probability: 0 = always a seabed, 1 = never a seabed, 0.15 = about 15% without.
# With a seabed, each existing Seabed_ mesh has an equal chance of selection.

# -----------------------------------------------------------------------------
# BACKGROUND STRUCTURES - frequency, requested count and asset names
# -----------------------------------------------------------------------------
USE_STRUCTURES_PROBABILITY = 0.40
# 0 = never request structures, 1 = always request them; actual placement can fail.
MIN_STRUCTURES_VISIBLE = 1  # Minimum requested when structures are enabled.
MAX_STRUCTURES_VISIBLE = 5  # Maximum requested; cannot exceed the list length.
STRUCTURE_NAMES = ['Old_Industrial_Pipe', 'Steel_Pillar_01', 'Steel_Pillar_02',
                   'Steel_Pillar_03', 'Steel_Pipe']
# Names must match roots in Background_Structures. Their children move with them.

# -----------------------------------------------------------------------------
# STRUCTURE PLACEMENT - background depth, rotation and spread across the image
# -----------------------------------------------------------------------------
STRUCTURE_DEPTH_MIN = 0.75  # Extra gap beyond the farthest chain bounds.
STRUCTURE_DEPTH_MAX = 3.0   # Maximum extra gap, on top of chain clearance below.
STRUCTURE_ROTATION_JITTER_DEG = 8.0  # Random Z rotation between -8 and +8 degrees.
STRUCTURE_FRAME_FRACTION_X = 0.8  # Horizontal placement range as a frame fraction.
STRUCTURE_FRAME_FRACTION_Y = 0.65  # Vertical placement range as a frame fraction.
# Larger fractions spread group centres towards the edges. These are candidate
# positions; geometry size, clearances and visibility determine acceptance.

# -----------------------------------------------------------------------------
# COLLISION CLEARANCES AND PLACEMENT CHECKS - scene units unless noted
# -----------------------------------------------------------------------------
CAMERA_CHAIN_CLEARANCE = 0.75  # Camera distance from each chain bounding box.
CAMERA_SEABED_CLEARANCE = 0.30  # Camera height above the local seabed surface.
STRUCTURE_CHAIN_CLEARANCE = 0.35  # Gap between structure and chain bounds.
STRUCTURE_CAMERA_CLEARANCE = 1.0  # Camera distance from structure bounds.
STRUCTURE_STRUCTURE_CLEARANCE = 0.20  # Gap between separate structure groups.
PLACEMENT_ATTEMPTS = 100  # Candidate positions tried for camera/each structure.
MIN_STRUCTURE_VISIBLE_RAYS = 2  # Surface samples that must be visible to accept.
# Larger gaps reject more placements. More attempts can help but take more time.

# -----------------------------------------------------------------------------
# WATER / FOG - vary density relative to the existing World volume in Blender
# -----------------------------------------------------------------------------
VARY_WATER = True  # False keeps the existing fog unchanged; it does NOT remove it.
WATER_DENSITY_MULTIPLIERS = (0.6, 1.5)
# Each eligible, unlinked World volume Density is multiplied by 0.6 to 1.5.
# Example: a saved density of 0.01 becomes 0.006 to 0.015 per image.
# Raise the multipliers for thicker haze; (1.0, 1.0) keeps the saved density.
# Set base density/colour in Blender's World shader. No new fog node is created.

# -----------------------------------------------------------------------------
# SEDIMENT PARTICLES - vary the existing ParticleCube particle system
# -----------------------------------------------------------------------------
VARY_PARTICLES = True  # False keeps existing particles; it does NOT hide them.
PARTICLE_COUNT_MULTIPLIERS = (0.55, 1.45)
# Fraction of the saved count: (0.55, 1.45) means 55% to 145% of the original.
PARTICLE_SIZE_MULTIPLIERS = (0.75, 1.25)
# Fraction of the saved particle size. Lower this pair for smaller particles.
# Example: (0.25, 0.50) gives particles one quarter to one half their saved size.
# Set both pairs to (1.0, 1.0) to fix count/size; particle positions still vary.
# Emitter shape, particle material and original simulation frame come from Blender.

# -----------------------------------------------------------------------------
# CHAIN POSE AND OTHER BLENDER SETTINGS
# -----------------------------------------------------------------------------
# Chain links retain their authored transforms: independent rotation can break
# their connections. Edit the chain pose in Blender, along with seabed materials,
# camera lens, render engine, sampling quality, exposure and colour management.

# -----------------------------------------------------------------------------
# IMPLEMENTATION BELOW - everyday render controls are in the settings above
# -----------------------------------------------------------------------------

# -----------------------------------------------------------------------------
# GEOMETRY HELPERS - world bounds, distances and intersection checks
# -----------------------------------------------------------------------------


def corners(obj, dg):
    ev = obj.evaluated_get(dg)
    return [ev.matrix_world @ Vector(c) for c in ev.bound_box]


def bounds(points):
    return tuple(Vector(tuple(fn(p[i] for p in points) for i in range(3))) for fn in (min,max))


def box_corners(box):
    a,b = box
    return [Vector((x,y,z)) for x in (a.x,b.x) for y in (a.y,b.y) for z in (a.z,b.z)]


def box_distance(point, box):
    a,b = box
    return math.sqrt(sum(max(a[i]-point[i],0,point[i]-b[i])**2 for i in range(3)))


def overlap(a,b,margin):
    return all(a[0][i] <= b[1][i]+margin and a[1][i] >= b[0][i]-margin for i in range(3))


# -----------------------------------------------------------------------------
# VISIBILITY HELPERS - objects, collections and camera surface-ray checks
# -----------------------------------------------------------------------------
def visible(obj,on):
    obj.hide_render = obj.hide_viewport = not on
    obj.hide_set(not on)


def enable_paths(layer,collections):
    needed = layer.collection in collections
    for child in layer.children:
        needed = enable_paths(child,collections) or needed
    if needed:
        layer.exclude = layer.hide_viewport = False
        layer.collection.hide_render = layer.collection.hide_viewport = False
    return needed


def in_frame(scene,camera,point):
    p = world_to_camera_view(scene,camera,point)
    return camera.data.clip_start < p.z < camera.data.clip_end and 0.02 < p.x < 0.98 and 0.02 < p.y < 0.98


def visible_rays(scene,dg,camera,group):
    """Sample actual surface points, including child meshes. Not a contrast test."""
    origin = camera.matrix_world.translation
    names = {o.name for o in group['meshes']}
    hits = 0
    for sample in group['samples']:
        point = group['root'].matrix_world @ sample
        if not in_frame(scene,camera,point):
            continue
        direction = point-origin
        hit,_,_,_,obj,_ = scene.ray_cast(dg,origin,direction.normalized(),distance=direction.length+0.1)
        if hit and obj.original.name in names:
            hits += 1
    return hits


# -----------------------------------------------------------------------------
# MAIN GENERATOR - validate scene, prepare a batch, render and restore state
# -----------------------------------------------------------------------------
def main():
    # -------------------------------------------------------------------------
    # SCENE VALIDATION - find the camera, links, seabeds, lights and structures
    # -------------------------------------------------------------------------
    if NUMBER_OF_IMAGES < 1 or PLACEMENT_ATTEMPTS < 1:
        raise ValueError('Image count and placement attempts must be positive.')
    scene = bpy.context.scene
    camera = scene.camera
    chain = bpy.data.collections.get('Chain_Links')
    structures = bpy.data.collections.get('Background_Structures')
    if camera is None or camera.data.type not in {'PERSP','ORTHO'} or chain is None or structures is None:
        raise RuntimeError('Need an active perspective/orthographic camera, Chain_Links and Background_Structures.')
    links = sorted((o for o in chain.all_objects if o.name.startswith('link_') and o.type=='MESH'),key=lambda o:o.name)
    seabeds = sorted((o for o in scene.objects if o.name.startswith('Seabed_') and o.type=='MESH'),key=lambda o:o.name)
    lights = [scene.objects.get(n) for n in ['Light_Left','Light_Right']]
    if not links or not seabeds or any(o is None or o.type!='LIGHT' for o in lights):
        raise RuntimeError('Missing chain meshes, seabed meshes, or named lights.')
    groups = []
    for name in STRUCTURE_NAMES:
        root = scene.objects.get(name)
        if root is None or root.name not in structures.all_objects:
            raise RuntimeError(f'Structure missing from Background_Structures: {name}')
        members = [root,*root.children_recursive]
        meshes = [o for o in members if o.type=='MESH']
        if not meshes:
            raise RuntimeError(f'Structure has no mesh geometry: {name}')
        groups.append(dict(root=root,members=members,meshes=meshes))
    if not 1 <= MIN_STRUCTURES_VISIBLE <= MAX_STRUCTURES_VISIBLE <= len(groups):
        raise ValueError('Structure count range must fit available groups.')
    controlled = {camera,*lights,*links,*seabeds}
    for group in groups:
        controlled.update(group['members'])
    if any(o.constraints or o.animation_data for o in [camera,*lights,*(g['root'] for g in groups)]):
        raise RuntimeError('Camera/lights/structure roots have constraints or animation; disable or bake first.')
    # -------------------------------------------------------------------------
    # SAVE ORIGINAL STATE - used to restore Blender even if a render fails
    # -------------------------------------------------------------------------
    states = {o:((o.location.copy(),o.rotation_euler.copy(),o.rotation_quaternion.copy(),
                  tuple(o.rotation_axis_angle),o.scale.copy()),o.hide_render,o.hide_viewport,o.hide_get())
              for o in controlled}
    collections = {c:(c.hide_render,c.hide_viewport) for c in bpy.data.collections}
    layers = []
    def remember(layer):
        layers.append((layer,layer.exclude,layer.hide_viewport))
        for child in layer.children:
            remember(child)
    remember(bpy.context.view_layer.layer_collection)
    render_state = (scene.render.resolution_x,scene.render.resolution_y,scene.render.resolution_percentage,
                    scene.render.filepath,scene.render.image_settings.file_format)
    frame,old_world = scene.frame_current,scene.world
    temporary_world = None
    particles = []
    light_state = [(o,o.data) for o in lights]
    seed_state = (scene.cycles.seed,scene.cycles.use_animated_seed)
    try:
        # ---------------------------------------------------------------------
        # PREPARE VISIBILITY, LIGHT COPIES AND OUTPUT RESOLUTION
        # ---------------------------------------------------------------------
        enable_paths(bpy.context.view_layer.layer_collection,{c for o in controlled for c in o.users_collection})
        for o in links+lights:
            visible(o,True)
        for o in lights:
            o.data = o.data.copy()
        scene.render.resolution_x,scene.render.resolution_y = IMAGE_WIDTH,IMAGE_HEIGHT
        scene.render.resolution_percentage = 100
        scene.render.image_settings.file_format = 'PNG'
        bpy.context.view_layer.update()
        dg = bpy.context.evaluated_depsgraph_get()
        # ---------------------------------------------------------------------
        # CACHE CHAIN BOUNDS AND STRUCTURE GEOMETRY, INCLUDING CHILD MESHES
        # ---------------------------------------------------------------------
        link_boxes = [bounds(corners(o,dg)) for o in links]
        centres = [(a+b)/2 for a,b in link_boxes]
        target = sum(centres,Vector())/len(centres)
        for g in groups:
            g['matrix'] = g['root'].matrix_world.copy()
            inverse = g['matrix'].inverted()
            g['corners'] = [inverse @ p for o in g['meshes'] for p in corners(o,dg)]
            g['samples'] = []
            for o in g['meshes']:
                ev = o.evaluated_get(dg)
                verts = ev.data.vertices
                step = max(1,len(verts)//24)
                g['samples'].extend(inverse @ (ev.matrix_world @ verts[i].co) for i in range(0,len(verts),step))
        # ---------------------------------------------------------------------
        # PREPARE TEMPORARY WATER AND PARTICLE SETTINGS
        # ---------------------------------------------------------------------
        water = []
        if VARY_WATER and old_world and old_world.use_nodes:
            temporary_world = old_world.copy()
            scene.world = temporary_world
            for n in temporary_world.node_tree.nodes:
                if n.type in {'VOLUME_SCATTER','VOLUME_PRINCIPLED','VOLUME_ABSORPTION'}:
                    socket = n.inputs.get('Density')
                    if socket and not socket.is_linked:
                        water.append((socket,socket.default_value))
        emitter = scene.objects.get('ParticleCube')
        if VARY_PARTICLES and emitter:
            for ps in emitter.particle_systems:
                if ps.point_cache.is_baked:
                    raise RuntimeError('ParticleCube cache is baked; free it before varying particles.')
                particles.append((ps,ps.settings,ps.seed))
                ps.settings = ps.settings.copy()
        # ---------------------------------------------------------------------
        # CREATE BATCH FOLDER, CONFIGURATION SNAPSHOT AND METADATA FILE
        # ---------------------------------------------------------------------
        master = MASTER_SEED if MASTER_SEED is not None else random.SystemRandom().randrange(2**31)
        folder = Path(OUTPUT_FOLDER)/datetime.now().strftime('run_%Y%m%d_%H%M%S_%f')
        folder.mkdir(parents=True,exist_ok=False)
        config = {k:v for k,v in globals().items() if k.isupper() and isinstance(v,(int,float,str,bool,list,tuple,type(None)))}
        config.update(actual_master_seed=master,blend_file=bpy.data.filepath,blender_version=bpy.app.version_string)
        (folder/'settings.json').write_text(json.dumps(config,indent=2),encoding='utf-8')
        (folder/'generator.py').write_text(Path(__file__).read_text(encoding='utf-8'),encoding='utf-8')
        fields = ['filename','seed','rendered','seabed','structures','skipped_structures','visible_rays',
                  'camera_matrix','structure_matrices','light_powers','water_densities','particles']
        with (folder/'metadata.csv').open('w',newline='',encoding='utf-8') as stream:
            writer = csv.DictWriter(stream,fieldnames=fields)
            writer.writeheader()
            for index in range(NUMBER_OF_IMAGES):
                # -------------------------------------------------------------
                # EACH IMAGE: 1. RESET STRUCTURES AND SELECT A SEABED
                # -------------------------------------------------------------
                seed = (master+index) % (2**31)
                rng = random.Random(seed)
                for g in groups:
                    g['root'].matrix_world = g['matrix'].copy()
                    for o in g['members']:
                        visible(o,False)
                chosen = None if rng.random()<NO_SEABED_PROBABILITY else rng.choice(seabeds)
                for o in seabeds:
                    visible(o,o==chosen)
                bpy.context.view_layer.update()
                # -------------------------------------------------------------
                # EACH IMAGE: 2. FIND A SAFE CAMERA POSITION AND AIM AT THE CHAIN
                # -------------------------------------------------------------
                for attempt in range(PLACEMENT_ATTEMPTS):
                    position = target+Vector((rng.uniform(-CAMERA_X_RANGE,CAMERA_X_RANGE),
                        rng.uniform(-CAMERA_Y_RANGE,CAMERA_Y_RANGE),rng.uniform(CAMERA_Z_MIN,CAMERA_Z_MAX)))
                    if any(box_distance(position,b)<CAMERA_CHAIN_CLEARANCE for b in link_boxes):
                        continue
                    if chosen:
                        ev = chosen.evaluated_get(dg)
                        inv = ev.matrix_world.inverted()
                        start = Vector((position.x,position.y,max(p.z for p in corners(chosen,dg))+1))
                        hit,loc,_,_ = ev.ray_cast(inv @ start,inv.to_3x3() @ Vector((0,0,-1)))
                        if hit and position.z<(ev.matrix_world @ loc).z+CAMERA_SEABED_CLEARANCE:
                            continue
                    camera.matrix_world = (target-position).to_track_quat('-Z','Y').to_matrix().to_4x4()
                    camera.matrix_world.translation = position
                    bpy.context.view_layer.update()
                    if sum(in_frame(scene,camera,p) for p in centres)>=MIN_VISIBLE_LINK_CENTRES:
                        break
                else:
                    raise RuntimeError(f'Image {index}: no safe camera position; increase camera ranges.')
                # -------------------------------------------------------------
                # EACH IMAGE: 3. PLACE STRUCTURES BEHIND THE CHAIN
                # -------------------------------------------------------------
                quat = camera.matrix_world.to_quaternion()
                right,up,forward = [quat @ Vector(a) for a in [(1,0,0),(0,1,0),(0,0,-1)]]
                far_chain = max((p-position).dot(forward) for b in link_boxes for p in box_corners(b))
                selected = groups if FORCE_STRUCTURES_FOR_TEST else (rng.sample(groups,rng.randint(
                    MIN_STRUCTURES_VISIBLE,MAX_STRUCTURES_VISIBLE)) if rng.random()<USE_STRUCTURES_PROBABILITY else [])
                placed,boxes,skipped,diagnostics = [],[],[],{}
                for g in selected:
                    for o in g['members']:
                        visible(o,True)
                    for attempt in range(PLACEMENT_ATTEMPTS):
                        matrix = Matrix.Rotation(math.radians(rng.uniform(-STRUCTURE_ROTATION_JITTER_DEG,
                            STRUCTURE_ROTATION_JITTER_DEG)),4,'Z') @ g['matrix']
                        matrix.translation = Vector()
                        points = [matrix @ p for p in g['corners']]
                        midpoint = sum(bounds(points),Vector())/2
                        points = [p-midpoint for p in points]
                        depth = far_chain+STRUCTURE_CHAIN_CLEARANCE+rng.uniform(STRUCTURE_DEPTH_MIN,
                            STRUCTURE_DEPTH_MAX)-min(p.dot(forward) for p in points)
                        frame_points = camera.data.view_frame(scene=scene)
                        scaled = [p*(depth/-p.z) if camera.data.type=='PERSP' else p for p in frame_points]
                        xs,ys = [p.x for p in scaled],[p.y for p in scaled]
                        centre = (
                            position + forward * depth
                            + right * rng.uniform(
                                min(xs) * STRUCTURE_FRAME_FRACTION_X,
                                max(xs) * STRUCTURE_FRAME_FRACTION_X,
                            )
                            + up * rng.uniform(
                                min(ys) * STRUCTURE_FRAME_FRACTION_Y,
                                max(ys) * STRUCTURE_FRAME_FRACTION_Y,
                            )
                        )
                        matrix.translation = centre-midpoint
                        box = bounds([p+centre for p in points])
                        if box_distance(position,box)<STRUCTURE_CAMERA_CLEARANCE or any(overlap(box,b,
                            STRUCTURE_CHAIN_CLEARANCE) for b in link_boxes) or any(overlap(box,b,
                            STRUCTURE_STRUCTURE_CLEARANCE) for b in boxes):
                            continue
                        g['root'].matrix_world = matrix
                        bpy.context.view_layer.update()
                        hits = visible_rays(scene,dg,camera,g)
                        if hits>=MIN_STRUCTURE_VISIBLE_RAYS:
                            placed.append(g)
                            boxes.append(box)
                            diagnostics[g['root'].name] = hits
                            break
                    else:
                        skipped.append(g['root'].name)
                        for o in g['members']:
                            visible(o,False)
                # Recheck earlier structures: a later placement may obscure them.
                for g in placed[:]:
                    hits = visible_rays(scene,dg,camera,g)
                    diagnostics[g['root'].name] = hits
                    if hits<MIN_STRUCTURE_VISIBLE_RAYS:
                        placed.remove(g)
                        skipped.append(g['root'].name)
                        for o in g['members']:
                            visible(o,False)
                        bpy.context.view_layer.update()
                # -------------------------------------------------------------
                # EACH IMAGE: 4. POSITION LIGHTS AND SELECT THEIR POWER
                # -------------------------------------------------------------
                base = rng.uniform(MIN_BASE_POWER,MAX_BASE_POWER)
                for light,side in zip(lights,[-1,1]):
                    light.matrix_world = camera.matrix_world.copy()
                    light.matrix_world.translation = position+right*side*LIGHT_SIDE_OFFSET+forward*LIGHT_FORWARD_OFFSET
                    light.data.energy = base * rng.uniform(
                        MIN_LIGHT_MULTIPLIER, MAX_LIGHT_MULTIPLIER
                    )
                # -------------------------------------------------------------
                # EACH IMAGE: 5. VARY WATER DENSITY AND PARTICLE COUNT / SIZE
                # -------------------------------------------------------------
                for socket,original in water:
                    socket.default_value = original*rng.uniform(*WATER_DENSITY_MULTIPLIERS)
                particle_log = []
                for ps,original,_ in particles:
                    ps.settings.count = max(1,round(original.count*rng.uniform(*PARTICLE_COUNT_MULTIPLIERS)))
                    ps.settings.particle_size = original.particle_size*rng.uniform(*PARTICLE_SIZE_MULTIPLIERS)
                    ps.seed = rng.randrange(100000)
                    particle_log.append(dict(count=ps.settings.count,size=ps.settings.particle_size,seed=ps.seed))
                if particles:
                    start = min(int(ps.settings.frame_start) for ps,_,_ in particles)
                    scene.frame_set(start-1)
                    for f in range(start,frame+1):
                        scene.frame_set(f)
                # -------------------------------------------------------------
                # EACH IMAGE: 6. RENDER PNG (UNLESS DRY_RUN IS ENABLED)
                # -------------------------------------------------------------
                scene.cycles.seed,scene.cycles.use_animated_seed = seed,False
                bpy.context.view_layer.update()
                filename = f'chain_{index:05d}.png'
                scene.render.filepath = str(folder/filename)
                print(f'{index+1}/{NUMBER_OF_IMAGES}: seabed={chosen.name if chosen else "NONE"}, structures={[g["root"].name for g in placed]}, skipped={skipped}',flush=True)
                if not DRY_RUN:
                    bpy.ops.render.render(write_still=True)
                # -------------------------------------------------------------
                # EACH IMAGE: 7. RECORD THE ACTUAL SETTINGS IN THE CSV
                # -------------------------------------------------------------
                matrix_list = lambda m:[list(row) for row in m]
                row = dict(filename=filename,seed=seed,rendered=not DRY_RUN,seabed=chosen.name if chosen else None,
                    structures=[g['root'].name for g in placed],skipped_structures=skipped,visible_rays=diagnostics,
                    camera_matrix=matrix_list(camera.matrix_world),structure_matrices={g['root'].name:
                    matrix_list(g['root'].matrix_world) for g in placed},light_powers=[o.data.energy for o in lights],
                    water_densities=[s.default_value for s,_ in water],particles=particle_log)
                writer.writerow({k:json.dumps(v) if isinstance(v,(list,dict)) else v for k,v in row.items()})
                stream.flush()
        print(f'Finished. Output: {folder}',flush=True)
        return folder
    finally:
        # ---------------------------------------------------------------------
        # RESTORE THE ORIGINAL SCENE AND REMOVE TEMPORARY DATA
        # ---------------------------------------------------------------------
        for ps,old,seed in particles:
            temporary = ps.settings
            ps.settings,ps.seed = old,seed
            bpy.data.particles.remove(temporary)
        scene.frame_set(frame)
        scene.world = old_world
        if temporary_world:
            bpy.data.worlds.remove(temporary_world)
        for o,old in light_state:
            temporary = o.data
            o.data = old
            if temporary!=old:
                bpy.data.lights.remove(temporary)
        for o,(transform,render,viewport,hidden) in states.items():
            o.location,o.rotation_euler,o.rotation_quaternion,o.rotation_axis_angle,o.scale = transform
            o.hide_render,o.hide_viewport = render,viewport
            o.hide_set(hidden)
        for c,(render,viewport) in collections.items():
            c.hide_render,c.hide_viewport = render,viewport
        for layer,excluded,hidden in layers:
            layer.exclude,layer.hide_viewport = excluded,hidden
        (scene.render.resolution_x,scene.render.resolution_y,scene.render.resolution_percentage,
         scene.render.filepath,scene.render.image_settings.file_format) = render_state
        scene.cycles.seed,scene.cycles.use_animated_seed = seed_state
        bpy.context.view_layer.update()


# -----------------------------------------------------------------------------
# ENTRY POINT - called by the Blender launcher or Blender's --python option
# -----------------------------------------------------------------------------
if __name__=='__main__':
    main()
